import React, { useEffect, useRef, useState } from 'react';
import { MdApi } from 'react-icons/md';
import './support.css';
import SupportTicket from '../pages/images/SupportTicket.svg';
import DarkSupportTicket from '../pages/images/DarkSupportTicket.svg';

import './ApiSdk.css';
import { FiX } from 'react-icons/fi';
import { CircleAlert, Clock, Headphones, Headset, Link, Link2, Plus, Search, UploadCloud } from 'lucide-react';

export default function Support() {
  const [showPopup, setShowPopup] = useState(false);
  const [isMobile, setIsMobile] = useState(window.innerWidth < 768);
  const [searchQuery, setSearchQuery] = useState('');
  const [isDarkMode, setIsDarkMode] = useState(false);
  const [activeTerm, setActiveTerm] = useState(false);
  const [openIndex, setOpenIndex] = useState(null);
  const [activeTab, setActiveTab] = useState("Enterprise");

  useEffect(() => {
    const checkTheme = () => {
      setIsDarkMode(document.documentElement.getAttribute('data-theme') === 'dark');
    };

    checkTheme();

    const observer = new MutationObserver(checkTheme);
    observer.observe(document.documentElement, {
      attributes: true,
      attributeFilter: ['data-theme'],
    });

    return () => observer.disconnect();
  }, []);

  React.useEffect(() => {
    const handleResize = () => setIsMobile(window.innerWidth < 768);
    window.addEventListener('resize', handleResize);
    return () => window.removeEventListener('resize', handleResize);
  }, []);

  const popularSearches = [
    'Upload images',
    'Setting up Payment',
    'Prompt Guide',
    '3D Model Export',
    'Fix Errors',
    'Credits & Billing',
    'API Integration',
    'Edit 3D Model',
    'Billing',
  ];

  const helpCategories = [
    {
      title: 'Basics',
      description: 'Discover how AI3D works and start creating your first 3D model.',
    },
    {
      title: 'Data and Privacy',
      description: 'Learn how we protect your uploads, prompts, and personal data.',
    },
    {
      title: 'Your Profile',
      description: 'Manage your account information and personal settings.',
    },
    {
      title: 'Subscription Billing',
      description: 'Find help with plans, credits, and payment management.',
    },
    {
      title: 'About Models',
      description: 'Explore model types, formats, and quality optimization tips.',
    },
    {
      title: 'AI Prompts & Image Guide',
      description:
        'Learn how to write effective text prompts and use clear images for accurate results.',
    },
  ];

  const faqs = [
    {
      question: 'What is AI3D Enterprise?',

      answer:
        'AI3D Enterprise is a customized solution for large organizations that need secure, scalable, and high-performance 3D generation tools for their teams and workflows.',
    },

    {
      question: 'How is the enterprise plan different from the team plan?',

      answer:
        'Simply click "Sign Up" on our website or mobile app, enter your details, and verify your email. You can start with a free trial immediately.',
    },

    {
      question: 'Is data generated by our company kept private?',

      answer:
        'You can upgrade anytime from your account dashboard by selecting a subscription plan and making a secure online payment.',
    },

    {
      question: 'How does licensing work for enterprise users?',

      answer:
        ' Yes-discounts are available for annual subscriptions, educational institutions, and bulk enterprise packages. Contact our sales team for details.',
    },
  ];

  const toggleFAQ = (index) => {
    setOpenIndex(openIndex === index ? null : index);
  };

  const trustedLogosRef = useRef(null);

  useEffect(() => {
    if (!isMobile || !trustedLogosRef.current) return;
    let scrollAmount = 0;
    const logoWidth = 140;
    const interval = setInterval(() => {
      scrollAmount += logoWidth;
      if (
        scrollAmount >=
        trustedLogosRef.current.scrollWidth - trustedLogosRef.current.clientWidth
      ) {
        scrollAmount = 0;
      }
      trustedLogosRef.current.scrollTo({
        left: scrollAmount,
        behavior: 'smooth',
      });
    }, 1800);
    return () => clearInterval(interval);
  }, [isMobile]);

  const accordionRef = useRef(null);

  // Close FAQ if clicked outside
  useEffect(() => {
    function handleClickOutside(event) {
      if (accordionRef.current && !accordionRef.current.contains(event.target)) {
        setOpenIndex(null);
      }
    }
    document.addEventListener('mousedown', handleClickOutside);
    return () => document.removeEventListener('mousedown', handleClickOutside);
  }, []);

  const handlePopularSearchClick = (term) => {
    setActiveTerm(term);
    setSearchQuery(term);
  };

  const handleSearchChange = (e) => {
    setSearchQuery(e.target.value);
  };

  return (
    <div style={{ background: isDarkMode ? '#000' : '#fdf8fc' }}>
      <div className="support-ticket-system-container">
        <h1 className="support-ticket-system-h1-tag">Hi Adam, we’re here to help.</h1>
        <p className="support-ticket-system-p-tag">Manage and track your support requests</p>

        <div className="support-tab-container mt-4">
        {["Individual", "Team", "Enterprise"].map((tab) => (
          <button
            key={tab}
            onClick={() => setActiveTab(tab)}
            className={activeTab === tab ? "active" : ""}
          >
            {tab}
          </button>
        ))}
      </div>

        <div className="live-chat-banner">
          <CircleAlert className="mt-1" color="#DE3996" size={18} />
          <div className="chat-content">
            <strong>Live Chat Support</strong>
            <p>
              Our dedicated Live Chat Support team is now available around the clock to assist you.
              Whether day or night, feel free to connect with us anytime. We're here to answer your
              questions, resolve your issues, and ensure you get the support you need whenever you
              need it.
            </p>
          </div>
        </div>

        <div className="popular-searches">
          {popularSearches.map((term, index) => (
            <button
              key={index}
              className={`popular-search-btn ${activeTerm === term ? 'active' : ''}`}
              onClick={() => handlePopularSearchClick(term)}
            >
              {term}
            </button>
          ))}
        </div>

        <h2 className="help-text-title">
          How Can We <span style={{ color: '#DE3996' }}>Help</span> You?
        </h2>

        <div className="search-bar-container">
          <input
            type="text"
            placeholder="Search for help, guide, and more.."
            value={searchQuery}
            onChange={handleSearchChange}
            className="search-input"
          />
          <button className="search-btn">
            <Search size={18} />
          </button>
        </div>

        {/* Or view your ticket history link */}
        <div className="ticket-history-link">
          <span>
            or <a href="/tickets">view your ticket history</a>
          </span>
        </div>

        <div className="help-categories-grid">
          {helpCategories.map((item, index) => (
            <div key={index} className="help-card">
              <div className="d-flex align-items-center gap-3">
                <span className="linear-span-bg">
                  <Clock size={18} />
                </span>
                <h3>{item.title}</h3>
              </div>
              <p>{item.description}</p>
              <button className="learn-more-btn mt-1">
                <Link2 size={16} />
                Visit
              </button>
            </div>
          ))}
        </div>

        <div className="aithreed">
          <section className="dropdown mt-5" id="FAQs">
            <div className="container-fluid">
              <h2 className="question-header">
                Frequently <span style={{ color: '#DE3996' }}>Ask</span> Questions
              </h2>
              {/* Accordion */}
              <div className="accordion" ref={accordionRef}>
                {faqs.map((faq, index) => (
                  <div className="accordion-item border-0 mb-3" key={index}>
                    <h2 className="accordion-header justify">
                      <button
                        className={`accordion-button fw-semibold widthh ${
                          openIndex === index ? '' : 'collapsed'
                        }`}
                        type="button"
                        onClick={() => toggleFAQ(index)}
                      >
                        {faq.question}
                        <span className="icon-container">
                          <i
                            className="fa-solid fa-plus icon-plus"
                            style={{ display: openIndex === index ? 'none' : 'inline' }}
                          ></i>
                          <i
                            className="fa-solid fa-minus icon-minus"
                            style={{ display: openIndex === index ? 'inline' : 'none' }}
                          ></i>
                        </span>
                      </button>
                    </h2>
                    {openIndex === index && (
                      <div className="accordion-collapse show">
                        <div className="cet">
                          <div className="accordion-body text-muted">{faq.answer}</div>
                        </div>
                      </div>
                    )}
                  </div>
                ))}
              </div>
            </div>
          </section>
        </div>

        <div className="support-center-container mt-5">
          <span style={{
            background: "#fff",
            borderRadius: "50%",
            padding: "10px",
            display: "inline-flex",
            alignItems: "center",
            justifyContent: "center",
            boxShadow : '0 0 4px #00000050'
          }}><Headset color='#DE3996' size={30} /></span>
          <h2>Welcome to <span style={{color : '#DE3996'}}>Support</span> Center!</h2>
          <p>You haven't created any support tickets yet. Browse our FAQs above to find quick answers, or <br /> create a new ticket if you need personalized assistance.</p>
          <button className='a3d-ticket-btn mt-2' onClick={() => setShowPopup(true)}><Plus size={16} /> Create Your First Ticket</button>
        </div>
        
      </div>
      {showPopup && <SupportTicketPopup onClose={() => setShowPopup(false)} />}
    </div>
  );
}

