import React, { useEffect, useRef, useState } from 'react';
import { MdApi } from 'react-icons/md';
import './support.css';
import SupportTicket from '../pages/images/SupportTicket.svg';
import DarkSupportTicket from '../pages/images/DarkSupportTicket.svg';
import BasicTicket from '../pages/images/BasicTicket.svg';
import PrivacyTicket from '../pages/images/PrivacyTicket.svg';
import ProgramTicket from '../pages/images/ProgramTicket.svg';
import BillingTicket from '../pages/images/BillingTicket.svg';
import ModelsTicket from '../pages/images/ModelsTicket.svg';
import ImageTicket from '../pages/images/ImageTicket.svg';
import Success from '../assets/images/success-img.png';
import { baseURL } from '../config';
import { useAuth } from '../context/AuthContext';
import './ApiSdk.css';
import { FiX } from 'react-icons/fi';
import {
  CircleAlert,
  Clock,
  Headphones,
  Headset,
  Link,
  Link2,
  Plus,
  Search,
  UploadCloud,
} from 'lucide-react';
import axios from 'axios';
import { toast } from 'react-toastify';

export default function Support() {
  const [showPopup, setShowPopup] = useState(false);
  const [isMobile, setIsMobile] = useState(window.innerWidth < 768);
  const [searchQuery, setSearchQuery] = useState('');
  const [isDarkMode, setIsDarkMode] = useState(false);
  const [activeTerm, setActiveTerm] = useState(false);
  const [openIndex, setOpenIndex] = useState(null);
  const [activeTab, setActiveTab] = useState('Enterprise');
  const { token } = useAuth();
  const [user, setUser] = useState(null);

  useEffect(() => {
    axios
      .get(`${baseURL}/user`, {
        headers: { Authorization: `Bearer ${token}` },
      })
      .then((res) => setUser(res.data.user))
      .catch(() => setUser(null));
  }, [token]);

  useEffect(() => {
    const checkTheme = () => {
      setIsDarkMode(document.documentElement.getAttribute('data-theme') === 'dark');
    };

    checkTheme();

    const observer = new MutationObserver(checkTheme);
    observer.observe(document.documentElement, {
      attributes: true,
      attributeFilter: ['data-theme'],
    });

    return () => observer.disconnect();
  }, []);

  React.useEffect(() => {
    const handleResize = () => setIsMobile(window.innerWidth < 768);
    window.addEventListener('resize', handleResize);
    return () => window.removeEventListener('resize', handleResize);
  }, []);

  const popularSearches = [
    'Upload images',
    'Setting up Payment',
    'Prompt Guide',
    '3D Model Export',
    'Fix Errors',
    'Credits & Billing',
    'API Integration',
    'Edit 3D Model',
    'Billing',
  ];

  const helpCategories = [
    {
      title: 'Basics',
      description: 'Discover how AI3D works and start creating your first 3D model.',
      icon: BasicTicket,
    },
    {
      title: 'Data and Privacy',
      description: 'Learn how we protect your uploads, prompts, and personal data.',
      icon: PrivacyTicket,
    },
    {
      title: 'Your Profile',
      description: 'Manage your account information and personal settings.',
      icon: ProgramTicket,
    },
    {
      title: 'Subscription Billing',
      description: 'Find help with plans, credits, and payment management.',
      icon: BillingTicket,
    },
    {
      title: 'About Models',
      description: 'Explore model types, formats, and quality optimization tips.',
      icon: ModelsTicket,
    },
    {
      title: 'AI Prompts & Image Guide',
      description:
        'Learn how to write effective text prompts and use clear images for accurate results.',
      icon: ImageTicket,
    },
  ];

  const faqs = [
    {
      question: 'What is AI3D Enterprise?',

      answer:
        'AI3D Enterprise is a customized solution for large organizations that need secure, scalable, and high-performance 3D generation tools for their teams and workflows.',
    },

    {
      question: 'How is the enterprise plan different from the team plan?',

      answer:
        'Simply click "Sign Up" on our website or mobile app, enter your details, and verify your email. You can start with a free trial immediately.',
    },

    {
      question: 'Is data generated by our company kept private?',

      answer:
        'You can upgrade anytime from your account dashboard by selecting a subscription plan and making a secure online payment.',
    },

    {
      question: 'How does licensing work for enterprise users?',

      answer:
        ' Yes-discounts are available for annual subscriptions, educational institutions, and bulk enterprise packages. Contact our sales team for details.',
    },
  ];

  const toggleFAQ = (index) => {
    setOpenIndex(openIndex === index ? null : index);
  };

  const trustedLogosRef = useRef(null);

  useEffect(() => {
    if (!isMobile || !trustedLogosRef.current) return;
    let scrollAmount = 0;
    const logoWidth = 140;
    const interval = setInterval(() => {
      scrollAmount += logoWidth;
      if (
        scrollAmount >=
        trustedLogosRef.current.scrollWidth - trustedLogosRef.current.clientWidth
      ) {
        scrollAmount = 0;
      }
      trustedLogosRef.current.scrollTo({
        left: scrollAmount,
        behavior: 'smooth',
      });
    }, 1800);
    return () => clearInterval(interval);
  }, [isMobile]);

  const accordionRef = useRef(null);

  // Close FAQ if clicked outside
  useEffect(() => {
    function handleClickOutside(event) {
      if (accordionRef.current && !accordionRef.current.contains(event.target)) {
        setOpenIndex(null);
      }
    }
    document.addEventListener('mousedown', handleClickOutside);
    return () => document.removeEventListener('mousedown', handleClickOutside);
  }, []);

  const handlePopularSearchClick = (term) => {
    setActiveTerm(term);
    setSearchQuery(term);
  };

  const handleSearchChange = (e) => {
    setSearchQuery(e.target.value);
    if (activeTerm && e.target.value !== activeTerm) {
      setActiveTerm(null);
    }
  };

  // Filtered results based on searchQuery
  const filteredCategories = searchQuery.trim()
    ? helpCategories.filter(
        (item) =>
          item.title.toLowerCase().includes(searchQuery.toLowerCase()) ||
          item.description.toLowerCase().includes(searchQuery.toLowerCase())
      )
    : helpCategories;

  const filteredFaqs = searchQuery.trim()
    ? faqs.filter(
        (faq) =>
          faq.question.toLowerCase().includes(searchQuery.toLowerCase()) ||
          faq.answer.toLowerCase().includes(searchQuery.toLowerCase())
      )
    : faqs;

  const hasNoResults =
    searchQuery.trim() && filteredCategories.length === 0 && filteredFaqs.length === 0;

  return (
    <div style={{ background: isDarkMode ? '#000' : '#fdf8fc' }}>
      <div className="support-ticket-system-container">
        <h1 className="support-ticket-system-h1-tag">
          Hi {user?.name || 'Adam'}, we’re here to help.
        </h1>
        <p className="support-ticket-system-p-tag">Manage and track your support requests</p>

        <div className="support-tab-container mt-4">
          {['Individual', 'Team', 'Enterprise'].map((tab) => (
            <button
              key={tab}
              onClick={() => setActiveTab(tab)}
              className={activeTab === tab ? 'active' : ''}
            >
              {tab}
            </button>
          ))}
        </div>

        <div className="live-chat-banner">
          <CircleAlert className="mt-1" color="#DE3996" size={18} />
          <div className="chat-content">
            <strong>Live Chat Support</strong>
            <p>
              Our dedicated Live Chat Support team is now available around the clock to assist you.
              Whether day or night, feel free to connect with us anytime. We're here to answer your
              questions, resolve your issues, and ensure you get the support you need whenever you
              need it.
            </p>
          </div>
        </div>

        <div className="popular-searches">
          {popularSearches.map((term, index) => (
            <button
              key={index}
              className={`popular-search-btn ${activeTerm === term ? 'active' : ''}`}
              onClick={() => handlePopularSearchClick(term)}
            >
              {term}
            </button>
          ))}
        </div>

        <h2 className="help-text-title">
          How Can We <span style={{ color: '#DE3996' }}>Help</span> You?
        </h2>

        <div className="search-bar-container">
          <input
            type="text"
            placeholder="Search for help, guide, and more.."
            value={searchQuery}
            onChange={handleSearchChange}
            onKeyDown={(e) => e.key === 'Escape' && setSearchQuery('')}
            className="search-input"
          />
          {searchQuery && (
            <button
              className="search-clear-btn"
              onClick={() => { setSearchQuery(''); setActiveTerm(null); }}
              title="Clear search"
            >
              ✕
            </button>
          )}
          <button className="search-btn">
            <Search size={18} />
          </button>
        </div>

        {/* Or view your ticket history link */}
        <div className="ticket-history-link">
          {user ? (
            <span>
              or <a href="/3dio/support-ticket-history">view your ticket history</a>
            </span>
          ) : (
            <span
              style={{ color: '#db0c0cff', cursor: 'not-allowed', textDecoration: 'underline' }}
            >
              view your ticket history (please log in first)
            </span>
          )}
        </div>

        {hasNoResults ? (
          <div className="search-no-results">
            <Search size={40} style={{ opacity: 0.3, marginBottom: '12px' }} />
            <h3>No results found</h3>
            <p>No help articles match <strong>"{searchQuery}"</strong>. Try a different keyword or <button className="link-btn" onClick={() => { setSearchQuery(''); setActiveTerm(null); }}>clear the search</button>.</p>
          </div>
        ) : (
          <div className="help-categories-grid">
            {filteredCategories.map((item, index) => (
              <div key={index} className="help-card">
                <div className="d-flex align-items-center gap-3">
                  <span className="linear-span-bg">
                    <img src={item.icon} alt={item.title} />
                  </span>
                  <h3>{item.title}</h3>
                </div>
                <p>{item.description}</p>
                <button className="learn-more-btn mt-1">
                  <Link2 size={16} />
                  Visit
                </button>
              </div>
            ))}
          </div>
        )}

        <div className="aithreed">
          <section className="dropdown mt-5" id="FAQs">
            <div className="container-fluid">
              <h2 className="question-header">
                Frequently <span style={{ color: '#DE3996' }}>Ask</span> Questions
              </h2>
              {/* Accordion */}
              <div className="accordion" ref={accordionRef}>
                {filteredFaqs.length > 0 ? filteredFaqs.map((faq, index) => (
                  <div className="accordion-item border-0 mb-3" key={index}>
                    <h2 className="accordion-header justify">
                      <button
                        className={`accordion-button fw-semibold widthh ${
                          openIndex === index ? '' : 'collapsed'
                        }`}
                        type="button"
                        onClick={() => toggleFAQ(index)}
                        style={{
                          backgroundColor: isDarkMode ? '#110e20' : '#f5f5f5',
                          color: isDarkMode ? '#fff' : '#414141',
                          border: isDarkMode ? '1px solid #2a2a2a' : '1px solid #eee',
                        }}
                      >
                        {faq.question}
                        <span className="icon-container">
                          <i
                            className="fa-solid fa-plus icon-plus"
                            style={{ display: openIndex === index ? 'none' : 'inline' }}
                          ></i>
                          <i
                            className="fa-solid fa-minus icon-minus"
                            style={{ display: openIndex === index ? 'inline' : 'none' }}
                          ></i>
                        </span>
                      </button>
                    </h2>
                    {openIndex === index && (
                      <div className="accordion-collapse show">
                        <div className="cet">
                          <div className="accordion-body">{faq.answer}</div>
                        </div>
                      </div>
                    )}
                  </div>
                )) : searchQuery.trim() ? null : null}
              </div>
            </div>
          </section>
        </div>

        <div className="support-center-container mt-5">
          <span
            style={{
              background: '#fff',
              borderRadius: '50%',
              padding: '10px',
              display: 'inline-flex',
              alignItems: 'center',
              justifyContent: 'center',
              boxShadow: '0 0 4px #00000050',
            }}
          >
            <Headset color="#DE3996" size={30} />
          </span>
          <h2>
            Welcome to <span style={{ color: '#DE3996' }}>Support</span> Center!
          </h2>
          <p>
            You haven't created any support tickets yet. Browse our FAQs above to find quick
            answers, or <br /> create a new ticket if you need personalized assistance.
          </p>
          <button
            className={`a3d-ticket-btn mt-2 ${!user ? 'disabled-danger' : ''}`}
            onClick={() => user && setShowPopup(true)}
            disabled={!user}
            title={!user ? 'Please log in to create a support ticket.' : ''}
            style={{
              cursor: !user ? 'not-allowed' : 'pointer',
              opacity: !user ? 0.6 : 1,
              backgroundColor: !user ? '#e0245e' : '',
              color: !user ? '#fff' : '',
            }}
          >
            <Plus size={16} /> Create Your First Ticket
          </button>
        </div>
      </div>
      {showPopup && <SupportTicketPopup onClose={() => setShowPopup(false)} />}
    </div>
  );
}

export const SupportTicketPopup = ({ onClose }) => {
  const [isMobile, setIsMobile] = useState(window.innerWidth < 768);
  const [isDarkMode, setIsDarkMode] = useState(false);
  const [subject, setSubject] = useState('');
  const [category, setCategory] = useState('Featured Issue');
  const [description, setDescription] = useState('');
  const [file, setFile] = useState(null);
  const [loading, setLoading] = useState(false);
  const [showSuccessPopup, setShowSuccessPopup] = useState(false);

  useEffect(() => {
    const checkTheme = () => {
      setIsDarkMode(document.documentElement.getAttribute('data-theme') === 'dark');
    };
    checkTheme();
    const observer = new MutationObserver(checkTheme);
    observer.observe(document.documentElement, {
      attributes: true,
      attributeFilter: ['data-theme'],
    });
    return () => observer.disconnect();
  }, []);

  useEffect(() => {
    const handleResize = () => setIsMobile(window.innerWidth < 768);
    window.addEventListener('resize', handleResize);
    return () => window.removeEventListener('resize', handleResize);
  }, []);

  useEffect(() => {
    if (showSuccessPopup) {
      const timer = setTimeout(() => {
        setShowSuccessPopup(false);
        if (onClose) onClose();
      }, 3000); // 3 seconds
      return () => clearTimeout(timer);
    }
  }, [showSuccessPopup, onClose]);

  const handleFileChange = (e) => {
    setFile(e.target.files[0]);
  };

  const handleSubmit = async (e) => {
    e.preventDefault();

    if (!subject || !description) {
      toast.error('Please fill in the subject and description fields.');
      return;
    }

    setLoading(true);
    try {
      const formData = new FormData();
      formData.append('subject', subject);
      formData.append('category', category);
      formData.append('description', description);

      if (file) {
        formData.append('attachment', file);
      }

      const response = await axios.post(`${baseURL}/support/ticket`, formData, {
        headers: {
          'Content-Type': 'multipart/form-data',
        },
      });

      console.log('Ticket Created:', response.data);
      setShowSuccessPopup(true);
      setSubject('');
      setCategory('Featured Issue');
      setDescription('');
      setFile(null);
    } catch (error) {
      console.error('Error submitting ticket:', error);
    } finally {
      setLoading(false);
    }
  };

  const handleReset = () => {
    setSubject('');
    setCategory('Featured Issue');
    setDescription('');
    setFile(null);
  };

  return (
    <>
      <div className="support-team-overlay">
        <div className="support-account-popup">
          <button className="support-close-btn" onClick={onClose}>
            <FiX />
          </button>

          <div className="row">
            <div className="col-md-6 d-flex flex-column align-items-center justify-content-center">
              <img src={isDarkMode ? DarkSupportTicket : SupportTicket} alt="Support" />
              <h2 className="support-ticket-h2-tag">Need Help?</h2>
              <p className="support-ticket-p-tag">
                We’re here to assist you. Submit a support ticket and our team will get back to you
                as soon as possible.
              </p>
            </div>

            {/* Right Section */}
            <div className="col-md-6 mt-3 p-0">
              <div className="support-ticket-form-container">
                <h2>Submit Support Ticket</h2>
                <p>Fill out the form below and we’ll get back to you within 24 hours.</p>

                <form className="ai3d-form mt-4" onSubmit={handleSubmit}>
                  <div className="mb-3">
                    <label className="form-label">Subject</label>
                    <input
                      type="text"
                      className="form-control"
                      placeholder="Name of the issue..."
                      value={subject}
                      onChange={(e) => setSubject(e.target.value)}
                    />
                  </div>

                  <div className="mb-3">
                    <label className="form-label">Category</label>
                    <select
                      className="form-control"
                      value={category}
                      onChange={(e) => setCategory(e.target.value)}
                    >
                      <option>Featured Issue</option>
                      <option>Technical Request</option>
                      <option>AI Processing</option>
                      <option>Bug</option>
                    </select>
                  </div>

                  <div className="mb-3">
                    <label className="form-label">Description</label>
                    <textarea
                      className="form-control"
                      rows="3"
                      maxLength={300}
                      placeholder="Please describe your issue..."
                      value={description}
                      onChange={(e) => setDescription(e.target.value)}
                    ></textarea>
                  </div>

                  <div className="mb-3">
                    <label className="form-label">Attachments (optional)</label>
                    <div className="upload-box">
                      <span
                        style={{ background: '#DE399612', borderRadius: '50%', padding: '5px' }}
                      >
                        <UploadCloud color="#DE3996" />
                      </span>
                      <p>Drop your file here or click to browse</p>
                      <small style={{ color: '#919191', margin: 0, fontWeight: '500' }}>
                        Supported formats: PDF, DOC, JPG, PNG
                      </small>
                      <input
                        type="file"
                        accept=".pdf,.doc,.jpg,.jpeg,.png"
                        style={{ display: 'none' }}
                        id="fileInput"
                        onChange={handleFileChange}
                      />
                      <button
                        type="button"
                        className="support-browse-btn"
                        onClick={() => document.getElementById('fileInput').click()}
                      >
                        {file ? file.name : 'Browse File'}
                      </button>
                    </div>
                  </div>

                  {/* Buttons */}
                  <div className="support-system-buttons">
                    <button type="submit" className="a3d-ticket-btn" disabled={loading}>
                      {loading ? 'Submitting...' : 'Submit Ticket'}
                    </button>
                    <button type="button" className="a3d-reset-btn" onClick={handleReset}>
                      Reset
                    </button>
                  </div>
                </form>
              </div>
            </div>
          </div>
        </div>
      </div>

      {showSuccessPopup && (
        <div className="ticket-success-popup-overlay" onClick={onClose}>
          <div className="ticket-success-popup">
            <img src={Success} alt="" />
            <h3>Ticket Submitted Successfully!</h3>
            <p>Your support ticket has been submitted. Our team will get back to you soon.</p>
          </div>
        </div>
      )}
    </>
  );
};
